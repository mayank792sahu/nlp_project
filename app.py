@st.cache_resource(show_spinner="Loading VADER...")
def load_vader():
    from finsent.models.vader_model import VaderModel
    return VaderModel()


@st.cache_resource(show_spinner="Loading Loughran-McDonald lexicon...")
def load_lm():
    from finsent.models.loughran_mcdonald import LoughranMcDonaldModel
    return LoughranMcDonaldModel()


@st.cache_resource(show_spinner="Loading TF-IDF+ML pipeline...")
def load_tfidf_ml():
    from finsent.models.tfidf_ml import TfidfMlModel
    model = TfidfMlModel()
    return model.load()


@st.cache_resource(show_spinner="Loading FinBERT (first load can take ~20s)...")
def load_finbert():
    from finsent.models.finbert_model import FinBertModel
    return FinBertModel()


def try_load(loader):
    try:
        return loader(), None
    except Exception as e:
        return None, str(e)


