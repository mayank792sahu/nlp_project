def sentiment_badge_html(label: str) -> str:
    color = sentiment_color(label)
    return f'<span class="sentiment-badge" style="background:{color}">{label}</span>'


# NOTE: every *_html builder below returns a single flat line with no embedded
# newlines or leading whitespace. Streamlit's markdown renderer treats a 4-space
# indented line as a Markdown code block, which silently swallows nested HTML
# (e.g. the meter bar) as literal text instead of rendering it — multi-line
# pretty-printed f-strings trip this even though a lone flat <div> does not.

def stat_tile_html(label: str, value: str, sub: str = "") -> str:
    sub_html = f'<div class="tile-sub">{sub}</div>' if sub else ""
    return (
        '<div class="stat-tile">'
        f'<div class="tile-label">{label}</div>'
        f'<div class="tile-value">{value}</div>'
        f'{sub_html}'
        '</div>'
    )


def model_card_html(display_name: str, label: str, proba: dict) -> str:
    color = sentiment_color(label)
    desc = MODEL_DESCRIPTIONS.get(display_name, "")
    if proba:
        pct = proba.get(label, 0.0) * 100
        meter = (
            '<div class="meter-wrap">'
            f'<div class="meter-track" style="background:{color}22">'
            f'<div class="meter-fill" style="width:{pct:.0f}%; background:{color}"></div>'
            '</div>'
            f'<div class="meter-pct">{pct:.0f}%</div>'
            '</div>'
        )
    else:
        meter = '<div class="meter-wrap"><span class="model-unavailable">no confidence score available</span></div>'

    return (
        '<div class="model-card">'
        '<div class="model-row">'
        f'<div class="model-name">{display_name}</div>'
        f'{sentiment_badge_html(label)}'
        f'{meter}'
        '</div>'
        f'<div class="model-desc">{desc}</div>'
        '</div>'
    )


def unavailable_card_html(display_name: str, error: str) -> str:
    desc = MODEL_DESCRIPTIONS.get(display_name, "")
    return (
        '<div class="model-card">'
        '<div class="model-row">'
        f'<div class="model-name">{display_name}</div>'
        f'<span class="model-unavailable">unavailable — {error}</span>'
        '</div>'
        f'<div class="model-desc">{desc}</div>'
        '</div>'
    )


