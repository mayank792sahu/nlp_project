def render_stat_tiles(comparison_df: pd.DataFrame, significance_df: pd.DataFrame | None):
    best_acc_row = comparison_df.loc[comparison_df["accuracy"].idxmax()]
    best_f1_row = comparison_df.loc[comparison_df["macro_f1"].idxmax()]
    best_neutral_row = comparison_df.loc[comparison_df["neutral_f1"].idxmax()]
    baseline_row = comparison_df.loc[comparison_df["macro_f1"].idxmin()]

    lift = best_f1_row["macro_f1"] - baseline_row["macro_f1"]

    if significance_df is not None and len(significance_df):
        n_sig = int(significance_df["significant"].sum())
        n_total = len(significance_df)
        sig_value = f"{n_sig}/{n_total}"
        sig_sub = "pairwise comparisons (McNemar's test)"
    else:
        sig_value, sig_sub = "—", "run the notebook to compute"

    tiles = "".join([
        stat_tile_html("Best accuracy", f'{best_acc_row["accuracy"]:.1%}', best_acc_row["model"]),
        stat_tile_html("Best macro-F1", f'{best_f1_row["macro_f1"]:.3f}', best_f1_row["model"]),
        stat_tile_html("Best neutral-class F1", f'{best_neutral_row["neutral_f1"]:.3f}', best_neutral_row["model"]),
        stat_tile_html("Macro-F1 lift, best vs. weakest", f"+{lift:.3f}",
                        f'{baseline_row["model"]} → {best_f1_row["model"]}'),
        stat_tile_html("Statistically significant", sig_value, sig_sub),
    ])
    st.markdown(f'<div class="tile-row">{tiles}</div>', unsafe_allow_html=True)


def results_dashboard_tab():
    st.caption("Generated by notebooks/report.ipynb — rerun it to refresh these after any changes.")

    tables_dir = resolve_path(CONFIG["results"]["tables_dir"])
    figures_dir = resolve_path(CONFIG["results"]["figures_dir"])

    comparison_path = tables_dir / "comparison.csv"
    if not comparison_path.exists():
        st.info("No results yet — run notebooks/report.ipynb first to generate them.")
        return

    comparison_df = pd.read_csv(comparison_path)
    significance_path = tables_dir / "significance.csv"
    significance_df = pd.read_csv(significance_path) if significance_path.exists() else None

    render_stat_tiles(comparison_df, significance_df)

    st.markdown("#### Model comparison")
    st.dataframe(
        comparison_df.style.format({
            "accuracy": "{:.1%}", "macro_precision": "{:.3f}", "macro_recall": "{:.3f}",
            "macro_f1": "{:.3f}", "neutral_f1": "{:.3f}",
        }).background_gradient(subset=["macro_f1"], cmap="Blues"),
        use_container_width=True, hide_index=True,
    )

    comparison_chart = figures_dir / "comparison.png"
    if comparison_chart.exists():
        st.image(str(comparison_chart))

    if significance_df is not None:
        st.markdown("#### Statistical significance")
        n_sig = int(significance_df["significant"].sum())
        st.caption(
            f"McNemar's exact test, pairwise on the shared test set — "
            f"{n_sig} of {len(significance_df)} pairwise differences are significant at p < 0.05."
        )
        display_sig = significance_df.copy()
        display_sig["p_value"] = display_sig["p_value"].apply(lambda p: f"{p:.2e}")
        st.dataframe(display_sig, use_container_width=True, hide_index=True)

    st.markdown("#### Confusion matrices")
    model_names = comparison_df["model"].tolist()
    cols = st.columns(2)
    for i, name in enumerate(model_names):
        safe_name = name.replace(" ", "_").replace("(", "").replace(")", "")
        cm_path = figures_dir / f"{safe_name}_confusion.png"
        if cm_path.exists():
            cols[i % 2].image(str(cm_path), use_container_width=True)

    hardest_path = tables_dir / "hardest_sentences.csv"
    if hardest_path.exists():
        st.markdown("#### Hardest sentences (wrong on 2+ models)")
        hardest_df = pd.read_csv(hardest_path)
        pred_cols = [c for c in hardest_df.columns if c.startswith("pred_")]
        display_cols = ["sentence", "true_label", "n_models_wrong"] + pred_cols
        column_config = {
            "sentence": st.column_config.TextColumn("Sentence", width="large"),
            "true_label": st.column_config.TextColumn("True", width="small"),
            "n_models_wrong": st.column_config.NumberColumn("# wrong", width="small"),
        }
        for c in pred_cols:
            column_config[c] = st.column_config.TextColumn(c.replace("pred_", ""), width="small")
        st.dataframe(
            hardest_df[display_cols].head(15), use_container_width=True,
            hide_index=True, column_config=column_config,
        )


