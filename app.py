def live_demo_tab():
    st.markdown("#### Classify a financial sentence with all four models")

    example_key = st.selectbox("Example sentences", list(EXAMPLE_SENTENCES.keys()))
    default_text = EXAMPLE_SENTENCES[example_key]
    sentence = st.text_area(
        "Sentence", value=default_text, height=90,
        placeholder="e.g. Operating margin improved despite a challenging market.",
    )

    if st.button("Classify", type="primary") and sentence.strip():
        vader, vader_err = try_load(load_vader)
        lm, lm_err = try_load(load_lm)
        tfidf_ml, tfidf_err = try_load(load_tfidf_ml)
        finbert, finbert_err = try_load(load_finbert)

        model_specs = [
            ("VADER", vader, vader_err),
            ("Loughran-McDonald", lm, lm_err),
            ("TF-IDF + ML", tfidf_ml, tfidf_err),
            ("FinBERT (zero-shot)", finbert, finbert_err),
        ]

        labels_seen = []
        cards_html = []
        for display_name, model, err in model_specs:
            if err:
                cards_html.append(unavailable_card_html(display_name, err))
                continue
            label = model.predict([sentence])[0]
            proba = model.predict_proba([sentence])
            proba = proba[0] if proba else None
            labels_seen.append(label)
            cards_html.append(model_card_html(display_name, label, proba))

        if labels_seen:
            unique_labels = set(labels_seen)
            if len(unique_labels) == 1:
                good = sentiment_color(labels_seen[0])
                st.markdown(
                    f'<div class="agreement-banner" style="background:{good}14; '
                    f'border-color:{good}; color:{good}">'
                    f'✓ All {len(labels_seen)} available models agree: {labels_seen[0].upper()}</div>',
                    unsafe_allow_html=True,
                )
            else:
                counts = pd.Series(labels_seen).value_counts()
                summary = ", ".join(f"{c} say {lbl}" for lbl, c in counts.items())
                st.markdown(
                    f'<div class="agreement-banner" style="background:#fab21914; '
                    f'border-color:#fab219; color:{TEXT_PRIMARY}">'
                    f"⚠ Models disagree — {summary}</div>",
                    unsafe_allow_html=True,
                )

        st.markdown("".join(cards_html), unsafe_allow_html=True)


